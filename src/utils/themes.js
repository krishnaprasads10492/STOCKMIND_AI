/** Get a theme by key, falling back to cyber-dark. Merges with defaults. */
export function getTheme(key) {
  const theme = THEMES[key] ?? THEMES['cyber-dark']
  return {
    ...DEFAULT_IDENTITY,
    ...theme,
    fonts:   { ...DEFAULT_IDENTITY.fonts,   ...(theme.fonts   ?? {}) },
    radii:   { ...DEFAULT_IDENTITY.radii,   ...(theme.radii   ?? {}) },
    motion:  { ...DEFAULT_IDENTITY.motion,  ...(theme.motion  ?? {}) },
    bg:      { ...DEFAULT_IDENTITY.bg,      ...(theme.bg      ?? {}) },
    shadows: { ...DEFAULT_IDENTITY.shadows, ...(theme.shadows ?? {}) },
  }
}
